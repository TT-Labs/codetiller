import { mkdir, readdir, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { stringify } from 'yaml'
import { adapterFor } from '../agents/index.js'
import type { Config } from '../config/config.js'
import type { RepoProfile } from '../dataset/task.js'
import { ensureDeps } from '../sandbox/deps.js'
import { type ModelGateway, modelAccess, runAccounted } from '../sandbox/gateway.js'
import type { Prices } from '../sandbox/prices.js'
import type { Sandbox } from '../sandbox/sandbox.js'
import { sha256 } from '../util/hash.js'
import type { GitWorkspaces } from '../workspace/git.js'
import { CONTEXT_TOKEN_BUDGET, estimateTokens } from './context.js'

export interface GenerateSkillSpec {
  repo: string
  commit: string
  name: string
  description: string
  prompt: string
  profile: RepoProfile
  config: Config // harness + model + limits used for generation
  skillsDir: string
  artifactsDir: string
}

/**
 * One-off onboarding skill, generated by the agent itself at a commit older than
 * every task's base_commit, from the repo alone (isolated workspace: no history, no issues/PRs).
 */
export async function generateSkill(
  spec: GenerateSkillSpec,
  deps: {
    sandbox: Sandbox
    workspaces: GitWorkspaces
    env: Record<string, string>
    gateway?: ModelGateway
    prices?: Prices
    log?: (m: string) => void
  },
) {
  const { sandbox, workspaces, log = () => {} } = deps
  await workspaces.ensureRepo(spec.repo, [spec.commit])
  const dir = join(spec.skillsDir, spec.name)
  await mkdir(dir, { recursive: true })
  const versions = (await readdir(dir)).map((f) => /^v(\d+)\.md$/.exec(f)?.[1]).filter(Boolean)
  const version = Math.max(0, ...versions.map(Number)) + 1
  const runDir = join(spec.artifactsDir, `skill-${spec.name}-v${version}`)
  await mkdir(runDir, { recursive: true })
  const promptFile = join(runDir, 'prompt.md')
  await writeFile(promptFile, spec.prompt)

  const ws = await workspaces.createIsolated(
    spec.repo,
    spec.commit,
    `skill-${spec.name}-v${version}`,
  )
  try {
    const nm = await ensureDeps(sandbox, spec.profile, ws, spec.repo, log)
    log(`generating ${spec.name} v${version} at ${spec.commit.slice(0, 7)} (${spec.config.model})`)
    const access = await modelAccess(deps.env, deps.gateway, {
      label: `skill ${spec.name} v${version}`,
      config: spec.config,
      prices: deps.prices,
    })
    const { agent: res } = await runAccounted(access, () =>
      adapterFor(spec.config.harness).run({
        sandbox,
        image: spec.profile.image,
        workspace: ws,
        promptFile,
        volumes: nm.volumes,
        tmpfs: nm.scratch,
        config: spec.config,
        env: access.env,
        network: access.network,
        offline: access.offline,
      }),
    )
    await writeFile(join(runDir, 'transcript.jsonl'), res.transcript)
    const body = res.finalText?.trim()
    if (res.exit !== 'ok' || !body) throw new Error(`generation failed: exit ${res.exit}`)
    const tokens = estimateTokens(body)
    if (tokens > CONTEXT_TOKEN_BUDGET) {
      throw new Error(`skill too long: ~${tokens} > ${CONTEXT_TOKEN_BUDGET} tokens (see ${runDir})`)
    }
    const meta = {
      name: spec.name,
      version,
      description: spec.description,
      generated_from: {
        repo: spec.repo,
        commit: spec.commit,
        model: spec.config.model,
        harness: spec.config.harness,
        prompt_hash: sha256(spec.prompt).slice(0, 16),
      },
    }
    const path = join(dir, `v${version}.md`)
    await writeFile(path, `---\n${stringify(meta)}---\n\n${body}\n`)
    return { path, version, tokens, cost: res.cost_usd }
  } finally {
    await workspaces.dispose(ws)
  }
}
